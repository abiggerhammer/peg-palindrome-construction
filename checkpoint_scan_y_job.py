"""Resumable checkpoint scan driven by the explicit Fischer--Paterson machine.

This is the same equal-input ``t=1`` Lemma-3.2 query as
:mod:`checkpoint_scan_job`, but all border information is generated by the
literal multihead transition table in :mod:`fp_algorithm_y_multihead`.

One :meth:`tick` performs exactly one transition of Algorithm Y, one transition
of its unary-Delta backpointer walker, or one constant-size bookkeeping action.
No failure array, Z array, Manacher array, or candidate answer is precomputed.

The frozen word and the three derived pattern strings are still materialized by
host-language slicing at construction time.  In the final online machine these
are produced by a linear two-head copying/reversal transducer; that mechanical
input-preparation layer is deliberately kept separate from this audit job.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum, auto

from pattern_prepare_multihead import (
    HALT as PREP_HALT,
    MACHINE as PREP_MACHINE,
    WP, WPRE, WSUF,
    initial_configuration as prep_initial_configuration,
    output_word as prep_output_word,
)

from fp_algorithm_y_multihead import (
    A,
    BACK_START,
    AFTER_BACK,
    HALT,
    MACHINE,
    MultiheadConfiguration,
    initial_configuration,
)


class _Phase(Enum):
    PREPARE = auto()
    BUILD_PLAIN = auto()
    WALK_PLAIN = auto()
    BUILD_PREFIX = auto()
    WALK_PREFIX = auto()
    BUILD_SUFFIX = auto()
    WALK_SUFFIX = auto()
    SWEEP = auto()
    DONE = auto()


@dataclass
class CheckpointCandidateYJob:
    """Find the specialized Lemma-3.3 checkpoint candidate.

    The result is the least gap ``d`` accepted by specialized Lemma 3.2, but
    only when the frozen checkpoint length lies in
    ``[(c-1)d, cd)`` and no earlier candidate remains alive through the base
    point.  This is the same selection made by
    :class:`checkpoint_scan_job.CheckpointCandidateScanJob`.
    """

    word: str
    c: int

    def __post_init__(self) -> None:
        if self.c <= 5:
            raise ValueError("the outer reversal proof requires c>5")
        if any(ch not in "01" for ch in self.word):
            raise ValueError("the audited machine currently uses the binary alphabet")
        self.n = len(self.word)
        self.patterns: tuple[str, str, str] | None = None
        self.prep_config = prep_initial_configuration(self.word) if self.n else None
        self.phase = _Phase.PREPARE if self.n else _Phase.DONE
        self.config: MultiheadConfiguration | None = None

        # Candidate flags indexed by gap d.  P is a period candidate; F is a
        # full-branch candidate after the palindromic-prefix intersection; S
        # is a partial-branch candidate from an even palindromic suffix.
        self.period = [False] * (self.n + 1)
        self.min_full: int | None = None
        self.min_partial: int | None = self.n if self.n else None
        self.least_gap: int | None = None

        self.candidate: int | None = None
        self.ticks = 0
        self.machine_steps = 0
        self.border_events = 0
        self.sweep_d = 1  # retained for backward-compatible diagnostics

    @property
    def done(self) -> bool:
        return self.phase is _Phase.DONE

    def _start_pattern(self, index: int, phase: _Phase) -> None:
        assert self.patterns is not None
        self.config = initial_configuration(self.patterns[index])
        self.phase = phase

    def _machine_tick(self, walk_phase: _Phase) -> None:
        assert self.config is not None
        if self.config.state == HALT:
            self.phase = walk_phase
            return
        MACHINE.step(self.config)
        self.machine_steps += 1

    def _current_border(self) -> int:
        assert self.config is not None and self.config.state in (HALT, AFTER_BACK)
        # Pattern tape position 0 is the sentinel; therefore A's absolute
        # position is exactly the current border length p+1.
        return self.config.heads[A]

    def _follow_border_or_advance(self, next_pattern: int | None, next_phase: _Phase) -> None:
        assert self.config is not None and self.config.state == HALT
        if self._current_border() > 0:
            self.config.state = BACK_START
            return
        if next_pattern is None:
            self.config = None
            self.phase = next_phase
        else:
            self._start_pattern(next_pattern, next_phase)

    def _plain_event(self) -> None:
        border = self._current_border()
        if border > 0:
            p = self.n - border
            if p % 2 == 0:
                self.period[p // 2] = True
            self.border_events += 1
            self.config.state = BACK_START
        else:
            # The full word itself is always a period.
            if self.n % 2 == 0:
                self.period[self.n // 2] = True
            self._start_pattern(1, _Phase.BUILD_PREFIX)

    def _prefix_event(self) -> None:
        border = self._current_border()
        if border > 0:
            if border <= self.n and border % 2 == 0:
                d = border // 2
                if self.period[d]:
                    # Prefix-border lengths are encountered in decreasing
                    # order, hence d decreases and the last successful value
                    # is the least full-branch gap.
                    self.min_full = d
            self.border_events += 1
            self.config.state = BACK_START
        else:
            self._start_pattern(2, _Phase.BUILD_SUFFIX)

    def _suffix_event(self) -> None:
        border = self._current_border()
        if border > 0:
            if border < self.n and border % 2 == 0:
                d = self.n - border // 2
                # Suffix-border lengths decrease, hence d increases.  The
                # first successful value is already the least partial gap.
                if self.min_partial == self.n:
                    self.min_partial = d
            self.border_events += 1
            self.config.state = BACK_START
        else:
            self.config = None
            choices = [d for d in (self.min_full, self.min_partial) if d is not None]
            self.least_gap = min(choices) if choices else None
            if self.least_gap is not None:
                base = (self.c - 1) * self.least_gap
                target = self.c * self.least_gap
                if base <= self.n < target:
                    self.candidate = self.least_gap
            self.phase = _Phase.DONE

    def _sweep_tick(self) -> None:
        # Kept only so old serialized phase names remain readable.  Current
        # code computes the minimum directly from the two monotone border
        # streams and never enters SWEEP.
        self.phase = _Phase.DONE

    def tick(self) -> bool:
        if self.done:
            raise RuntimeError("checkpoint job already complete")
        self.ticks += 1

        if self.phase is _Phase.PREPARE:
            assert self.prep_config is not None
            if self.prep_config.state != PREP_HALT:
                PREP_MACHINE.step(self.prep_config)
                self.machine_steps += 1
            else:
                self.patterns = (
                    prep_output_word(self.prep_config, 1, self.prep_config.heads[WP]),
                    prep_output_word(self.prep_config, 2, self.prep_config.heads[WPRE]),
                    prep_output_word(self.prep_config, 3, self.prep_config.heads[WSUF]),
                )
                self.prep_config = None
                self._start_pattern(0, _Phase.BUILD_PLAIN)
        elif self.phase is _Phase.BUILD_PLAIN:
            self._machine_tick(_Phase.WALK_PLAIN)
        elif self.phase is _Phase.WALK_PLAIN:
            if self.config is not None and self.config.state not in (HALT, AFTER_BACK):
                MACHINE.step(self.config)
                self.machine_steps += 1
            else:
                self._plain_event()
        elif self.phase is _Phase.BUILD_PREFIX:
            self._machine_tick(_Phase.WALK_PREFIX)
        elif self.phase is _Phase.WALK_PREFIX:
            if self.config is not None and self.config.state not in (HALT, AFTER_BACK):
                MACHINE.step(self.config)
                self.machine_steps += 1
            else:
                self._prefix_event()
        elif self.phase is _Phase.BUILD_SUFFIX:
            self._machine_tick(_Phase.WALK_SUFFIX)
        elif self.phase is _Phase.WALK_SUFFIX:
            if self.config is not None and self.config.state not in (HALT, AFTER_BACK):
                MACHINE.step(self.config)
                self.machine_steps += 1
            else:
                self._suffix_event()
        elif self.phase is _Phase.SWEEP:
            self._sweep_tick()
        else:  # pragma: no cover
            raise AssertionError(self.phase)
        return self.done

    def run(self, *, max_ticks: int = 10_000_000) -> int | None:
        while not self.done:
            if self.ticks >= max_ticks:
                raise TimeoutError((self.phase, self.n, self.ticks))
            self.tick()
        return self.candidate
